let currentLanguage = localStorage.getItem('dropsite_lang') || 'en';

/**
 * Get translation for given key
 */
function t(key, defaultVal = '') {
    const langDict = translations[currentLanguage] || translations['en'];
    if (langDict && langDict[key] !== undefined) {
        return langDict[key];
    }
    const enDict = translations['en'];
    if (enDict && enDict[key] !== undefined) {
        return enDict[key];
    }
    return defaultVal || key;
}

/**
 * Change the active language across the entire application
 */
function setLanguage(lang) {
    if (!translations[lang]) {
        lang = 'en';
    }
    currentLanguage = lang;
    localStorage.setItem('dropsite_lang', lang);
    document.documentElement.lang = lang;

    // Update current badge in navbar
    const langLabel = document.getElementById('currentLangLabel');
    if (langLabel) {
        langLabel.textContent = lang.toUpperCase();
    }

    // Update all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const text = t(key);
        if (text) {
            el.textContent = text;
        }
    });

    // Update all inputs with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        const text = t(key);
        if (text) {
            el.setAttribute('placeholder', text);
        }
    });

    // Update elements with data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        const text = t(key);
        if (text) {
            el.setAttribute('title', text);
        }
    });

    // Mark active item in dropdown
    document.querySelectorAll('.lang-option').forEach(btn => {
        btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });

    // Trigger custom event for other scripts
    document.dispatchEvent(new CustomEvent('dropsite_language_changed', { detail: { lang } }));
}

// Initialize language on startup
document.addEventListener('DOMContentLoaded', () => {
    // Auto-detect browser language if not set yet
    if (!localStorage.getItem('dropsite_lang')) {
        const userLang = (navigator.language || navigator.userLanguage || 'en').slice(0, 2).toLowerCase();
        if (translations[userLang]) {
            currentLanguage = userLang;
        } else {
            currentLanguage = 'en';
        }
    }

    setLanguage(currentLanguage);

    // Dropdown toggle logic
    const langSelectBtn = document.getElementById('langSelectBtn');
    const langMenu = document.getElementById('langMenu');

    if (langSelectBtn && langMenu) {
        langSelectBtn.addEventListener('click', (e) => {
            e.stopPropagation();
            const isHidden = langMenu.hidden;
            langMenu.hidden = !isHidden;
            langSelectBtn.classList.toggle('active', isHidden);
        });

        document.addEventListener('click', (e) => {
            if (!langMenu.contains(e.target) && e.target !== langSelectBtn) {
                langMenu.hidden = true;
                langSelectBtn.classList.remove('active');
            }
        });

        langMenu.querySelectorAll('.lang-option').forEach(btn => {
            btn.addEventListener('click', () => {
                const selectedLang = btn.getAttribute('data-lang');
                if (selectedLang) {
                    setLanguage(selectedLang);
                    langMenu.hidden = true;
                    langSelectBtn.classList.remove('active');
                }
            });
        });
    }
});

// Expose globally
window.t = t;
window.setLanguage = setLanguage;
window.currentLanguage = () => currentLanguage;
